/// Writes the home screen widget's Android color resources from the app's
/// color tokens (feature 008 T137a; Constitution V, spec §15.2: hex values
/// come from one source).
///
/// The tokens need Flutter's `ColorScheme.fromSeed`, which only runs under
/// the Flutter engine, so the generation runs through the sync test:
///
/// ```sh
/// UPDATE_WIDGET_COLORS=1 flutter test test/android/widget_colors_sync_test.dart
/// ```
///
/// Without the variable the test fails when the XML and the tokens differ.
library;

/// Resource names, in file order (contracts/android.md).
const List<String> widgetColorNames = [
  'widget_surface',
  'widget_on_surface',
  'widget_on_surface_variant',
  'widget_success',
  'widget_warning',
  'widget_expense',
];

/// `values/widget_colors.xml` or `values-night/widget_colors.xml` for
/// [argb], keyed by [widgetColorNames].
String widgetColorsXml(Map<String, int> argb, {required bool night}) {
  final theme = night ? 'dark' : 'light';
  final lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- GENERATED by tool/android/widget_colors.dart from AppColors',
    '     and AppTheme ($theme). Do not edit by hand. -->',
    '<resources>',
    for (final name in widgetColorNames)
      '    <color name="$name">#${_hex(argb[name]!)}</color>',
    '</resources>',
  ];
  return '${lines.join('\n')}\n';
}

String _hex(int argb) =>
    (argb & 0xFFFFFFFF).toRadixString(16).padLeft(8, '0').toUpperCase();
