def main() -> None:
    out_dir = pathlib.Path(__file__).resolve().parents[2] / "lib" / "core" / "l10n"
    for idx, lang in enumerate(["en", "hi", "gu"]):
        arb = {"@@locale": lang}
        for key, (*values, desc) in S.items():
            arb[key] = values[idx]
            if lang == "en":
                meta = {"description": desc}
                if key in PLACEHOLDERS:
                    meta["placeholders"] = PLACEHOLDERS[key]
                arb[f"@{key}"] = meta
        for code, names in CURRENCIES.items():
            arb[f"currency_{code}"] = names[idx]
            if lang == "en":
                arb[f"@currency_{code}"] = {"description": f"Display name of {code} (SYS-02 step 2)."}
        (out_dir / f"app_{lang}.arb").write_text(
            json.dumps(arb, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )

    # Key -> getter lookup for strings stored as data (currency names, module
    # names, seeded category names). Placeholder strings are excluded.
    keys = [k for k in S if k not in PLACEHOLDERS] + [f"currency_{c}" for c in CURRENCIES]
    cases = "\n".join(f"  '{k}' => l10n.{k}," for k in keys)
    dart = (
        "// GENERATED by tool/l10n/phase0_strings.py. Do not edit by hand.\n\n"
        "import 'package:dailytrack/core/l10n/gen/app_localizations.dart';\n\n"
        "/// Resolves an ARB key stored as data (e.g. `currency_USD`, `modules_water`,\n"
        "/// `expense_cat_food`) to its translation, or null if the key is unknown.\n"
        "String? l10nByKey(AppLocalizations l10n, String key) => switch (key) {\n"
        f"{cases}\n"
        "  _ => null,\n"
        "};\n"
    )
    (out_dir / "l10n_lookup.dart").write_text(dart, encoding="utf-8")


if __name__ == "__main__":
    main()
